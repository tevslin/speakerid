"""
Data schemas for `speakerid` (`speakerid.schemas`).

Purpose (BoM):
    Defines Pydantic models for Deepgram-compatible transcription outputs,
    speaker identification and time-bound override mappings, timestamped
    agenda items and summaries, and the unified SmartTranscript™ output payload.

Dual-Use Schema Reference (Human & LLM):
    1. `DeepgramResponse`:
       - `metadata`: Request ID, duration, model details, diagnostics timing.
       - `results.channels[0].alternatives[0]`:
           * `transcript`: Full plain-text transcript.
           * `words`: Word-level start/end timestamps, confidence, integer speaker ID.
           * `paragraphs.paragraphs`: Grouped speaker turns with `sentences` (`text`, `start`, `end`).
    2. `SpeakerIdentificationResult`:
       - `speakers`: List of `SpeakerEntry` (`speaker_id`, `speaker_name`, `reason`,
         `confidence_level`, optional `start_time` / `end_time` for overlap overrides).
       - `agenda_items`: List of `AgendaItem` (`title`, `start_time`, `summary`).
    3. `SmartTranscriptOutput`:
       - Top-level container returned by `create_smart_transcript()`.
"""

from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field


class ModelInfo(BaseModel):
    """Metadata representing ASR model details."""
    name: str
    version: str = "v3"
    arch: str = "whisperx"


class Metadata(BaseModel):
    """Metadata about the transcription request and execution diagnostics."""
    transaction_key: str = "local"
    request_id: str
    sha256: str = ""
    created: str
    duration: float
    channels: int = 1
    models: List[str] = Field(default_factory=list)
    model_info: Dict[str, ModelInfo] = Field(default_factory=dict)
    diagnostics: Optional[Dict[str, Any]] = None


class Word(BaseModel):
    """Represents a single word token with phonetic alignment and speaker ID."""
    word: str
    start: float
    end: float
    confidence: float
    speaker: Optional[int] = None
    speaker_confidence: Optional[float] = None
    punctuated_word: Optional[str] = None


class ParagraphSentence(BaseModel):
    """A single sentence within a speaker paragraph."""
    text: str
    start: float
    end: float


class ParagraphElement(BaseModel):
    """A paragraph block grouping consecutive sentences by the same speaker."""
    speaker: int
    num_words: int
    start: float
    end: float
    sentences: List[ParagraphSentence] = Field(default_factory=list)


class ParagraphsData(BaseModel):
    """Container for transcript text and speaker-segmented paragraphs."""
    transcript: str
    paragraphs: List[ParagraphElement] = Field(default_factory=list)


class Alternative(BaseModel):
    """Single transcription alternative containing words and paragraphs."""
    transcript: str
    confidence: float
    words: List[Word] = Field(default_factory=list)
    paragraphs: Optional[ParagraphsData] = None


class Channel(BaseModel):
    """Represents a single audio channel's transcription alternatives."""
    alternatives: List[Alternative]


class Utterance(BaseModel):
    """An utterance segment representing a contiguous turn of speech."""
    start: float
    end: float
    confidence: float
    channel: int = 0
    transcript: str
    words: List[Word] = Field(default_factory=list)
    speaker: Optional[int] = None
    id: str


class Results(BaseModel):
    """Container for channel results and optional utterance segments."""
    channels: List[Channel]
    utterances: Optional[List[Utterance]] = None


class DeepgramResponse(BaseModel):
    """Root Deepgram-compatible transcription response structure."""
    metadata: Metadata
    results: Results


class SpeakerEntry(BaseModel):
    """Speaker identity mapping deduced by the LLM, optionally scoped to a time window."""
    speaker_id: Union[str, int]
    speaker_name: str
    reason: Optional[str] = ""
    confidence_level: Optional[int] = 0
    start_time: Optional[float] = None
    end_time: Optional[float] = None


class AgendaItem(BaseModel):
    """Timestamped chapter/agenda item generated by the LLM."""
    title: str
    start_time: float
    summary: str


class SpeakerIdentificationResult(BaseModel):
    """Structured output returned by the LLM speaker & agenda analyzer."""
    speakers: List[SpeakerEntry] = Field(default_factory=list)
    agenda_items: List[AgendaItem] = Field(default_factory=list)


class SmartTranscriptOutput(BaseModel):
    """Complete result object returned by the SmartTranscript pipeline."""
    status: str = "success"
    request_id: str
    title: str
    audio_path: str
    media_url: Optional[str] = None
    jurisdiction: str = ""
    transcription: Dict[str, Any]
    speaker_id_analysis: Optional[Dict[str, Any]] = None
    json_output_path: Optional[str] = None
    html_output_path: Optional[str] = None
